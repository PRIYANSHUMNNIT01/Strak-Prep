export const toggleSolvedQuestion = (id) => {
  try {
    const current = getSolvedQuestions();
    const updated = current.includes(id) ? current.filter(x => x !== id) : [...current, id];
    localStorage.setItem("starkprep_solved_questions", JSON.stringify(updated));
    return updated;
  } catch (e) {
    return [];
  }
};
